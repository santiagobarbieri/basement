import assert from 'node:assert/strict';
import {exportGeometry,exportState} from '../dist/document-bounds.js';
import {serializeMent,documentSignature} from '../dist/ment-format.js';
import {importMent} from '../dist/project-store.js';
import {normalizeEndoState,addFrame} from '../dist/endo-model.js';
const settings={width:20,primary:'#8795a8',shadow:'#10141b',contrast:'#eff5ff'};
const stroke=x=>({number:x,settings,tool:{mode:'none'},points:[{x,y:10,time:0,pressure:1}]});
let state=normalizeEndoState({infinite:true,scene:{},defaults:{},tool:{mode:'none'},nextNumber:3,strokes:[stroke(10),stroke(100000)]});
state=addFrame(state,{id:'poster',name:'My work',x:-10,y:-20,width:100,height:80});
assert.deepEqual(exportGeometry(state),{x:-10,y:-20,width:200,height:160,name:'My work',frameId:'poster',background:null});
assert.equal(exportState(state).strokes.length,0,'An empty frame does not export strokes from other frames');
assert.equal(exportGeometry({...state,exportTarget:'selection',selection:[0]}).frameId,'poster','Selection is no longer a download area');
assert.ok(exportGeometry({...state,exportTarget:'frame-1'}).width<=4096);
const doc=serializeMent(state,{id:'qa',name:'Full project'}),imported=importMent(doc);assert.equal(imported.state.strokes.length,2);assert.deepEqual(imported.state.frames,state.frames);
assert.equal(documentSignature({...state,selection:[],exportTarget:'poster'}),documentSignature(state));
const malformed=JSON.parse(doc);malformed.artboard.settings.frames[0].width=-1;assert.throws(()=>importMent(JSON.stringify(malformed)),/invalid frame/);
console.log('PASS finite frame-only downloads, cross-frame isolation, portable full document and frame dimension validation');
